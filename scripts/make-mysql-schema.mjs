// What: writes prisma/mysql/schema.prisma from prisma/schema.prisma, so the MySQL (Amazon RDS) schema never drifts from the SQLite one.
// Who calls it: `npm install` (postinstall), before `prisma generate`. A test checks that the committed copy is up to date.
// To extend: change prisma/schema.prisma only, then run `node scripts/make-mysql-schema.mjs` (or `npm install`).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The MySQL schema text for a given SQLite schema text. Exported for the test. */
export function toMysqlSchema(sqliteSchema) {
  const lines = sqliteSchema.split("\n").map((line) => {
    // Long text columns: SQLite has no length limit; MySQL's default VARCHAR(191) would cut them off, and TEXT stops at 64 KB.
    if (/^\s+\w+\s+String\??\s.*\/\/\s*LONG TEXT/.test(line) && !line.includes("@db.")) {
      return line.replace(/^(\s+\w+\s+String\??)(\s+)/, "$1 @db.LongText$2");
    }
    return line;
  });
  return [
    "// GENERATED by scripts/make-mysql-schema.mjs from prisma/schema.prisma. Do not edit; edit prisma/schema.prisma instead.",
    "// Used when DATABASE_URL starts with mysql:// (Amazon RDS for MySQL). See docs/AWS_DEPLOY.md.",
    ...lines,
  ]
    .join("\n")
    .replace('provider = "sqlite"', 'provider = "mysql"')
    .replace('output   = "../src/generated/prisma"', 'output   = "../../src/generated/prisma-mysql"');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const source = readFileSync(path.join(root, "prisma", "schema.prisma"), "utf8");
  const target = path.join(root, "prisma", "mysql", "schema.prisma");
  if (process.argv.includes("--check")) {
    // Used by the tests: fails when someone edited prisma/schema.prisma without regenerating the MySQL copy.
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // missing counts as out of date
    }
    if (current !== toMysqlSchema(source)) {
      console.error("prisma/mysql/schema.prisma is out of date. Run: node scripts/make-mysql-schema.mjs");
      process.exit(1);
    }
    console.log("prisma/mysql/schema.prisma is up to date.");
    process.exit(0);
  }
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, toMysqlSchema(source));
  console.log("prisma/mysql/schema.prisma written.");
}
