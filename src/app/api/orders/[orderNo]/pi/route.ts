// What: route handler that returns the proforma invoice (PI) of an exported order as a PDF download.
// Who calls it: the "Download PI (PDF)" button on the order page.
// To extend: the PI layout is in src/adapters/pdf/proformaInvoicePdf.ts. The content comes from the approved export, never from a draft.
import { actorOf, getPersona } from "@/app/_lib/session";
import { renderProformaInvoice } from "@/adapters/pdf/proformaInvoicePdf";
import { piNumberFor } from "@/domain/po/exportFile";
import { businessDate } from "@/domain/time";
import { recordAudit } from "@/services/audit";
import { getDeps } from "@/services/deps";
import { exportedOrderFile } from "@/services/poExport";

const PI_FOOTER = "SYNTHETIC SAMPLE - proforma invoice generated by the Spectra OrderFlow POC from sample data. Not a real document.";

export async function GET(_request: Request, context: RouteContext<"/api/orders/[orderNo]/pi">): Promise<Response> {
  const persona = await getPersona();
  if (!persona) return new Response("Pick a persona first.", { status: 401 });
  const { orderNo } = await context.params;
  const deps = await getDeps();
  const order = await deps.db.order.findUnique({ where: { orderNo } });
  const file = order ? await exportedOrderFile(deps, orderNo) : null;
  if (!order || !file) return new Response("This order has not been approved and exported yet, so it has no PI.", { status: 404 });

  const piNumber = order.piNumber ?? piNumberFor(orderNo);
  const bytes = await renderProformaInvoice(
    {
      piNumber,
      piDate: businessDate(order.piIssuedAt ?? deps.clock.now()),
      sellerName: "Spectra Innovations",
      customerName: file.customer.name,
      poNumber: file.customerPoNumber,
      currency: file.currency,
      paymentTerms: file.paymentTerms === "advance" ? "Advance payment" : "Credit",
      lines: file.lines,
      totalAmount: file.totalAmount,
    },
    PI_FOOTER,
  );
  await recordAudit(deps, {
    actor: actorOf(persona),
    action: "pi_downloaded",
    entityType: "order",
    entityId: orderNo,
    orderNo,
    summary: `${persona.name} downloaded ${piNumber} as a PDF.`,
  });
  return new Response(Buffer.from(bytes), {
    headers: { "Content-Type": "application/pdf", "Content-Disposition": `attachment; filename="${piNumber}.pdf"` },
  });
}
